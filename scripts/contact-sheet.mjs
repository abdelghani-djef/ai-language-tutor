#!/usr/bin/env node
// Writes docs/pictures.html: a contact sheet of every chosen picture in public/scenes/*.json,
// with the word or place under it and its credit. Plain Node, no dependencies.
// Run: node scripts/contact-sheet.mjs
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const scenesDir = join(root, "public", "scenes");
const outFile = join(root, "docs", "pictures.html");

const esc = (s) =>
  String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const safeUrl = (u) => (/^https?:\/\//i.test(String(u ?? "")) ? esc(u) : "");
const read = (f) => JSON.parse(readFileSync(join(scenesDir, f), "utf8"));

function card(label, pic) {
  const thumb = safeUrl(pic.thumb);
  const page = safeUrl(pic.page);
  const author = esc(pic.author || "Unknown author");
  const licence = esc(pic.licence || "licence not stated");
  const caption = pic.caption ? `<div class="cap">${esc(pic.caption)}</div>` : "";
  return `<figure>
<a href="${page}" target="_blank" rel="noopener"><img src="${thumb}" alt="${esc(label)}" loading="lazy" decoding="async"></a>
<figcaption><strong>${esc(label)}</strong>${caption}<div class="credit">${author} · ${licence} · <a href="${page}" target="_blank" rel="noopener">page</a></div></figcaption>
</figure>`;
}

const sections = [];
let total = 0;
let wordsWithNone = 0;
let totalWords = 0;

// Places first.
const places = read("_places.json");
{
  const cards = [];
  let none = 0;
  for (const [key, p] of Object.entries(places)) {
    if (p.picture) cards.push(card(`${p.emoji ?? ""} ${p.label?.en ?? key}`.trim(), p.picture));
    else none++;
  }
  total += cards.length;
  sections.push({ title: "Places", cards, note: `${cards.length} pictures, ${none} places without one` });
}

// Then every list.
for (const f of readdirSync(scenesDir).filter((n) => n.endsWith(".json") && n !== "_places.json").sort()) {
  const pack = read(f);
  const cards = [];
  let none = 0;
  for (const [word, entry] of Object.entries(pack.words ?? {})) {
    totalWords++;
    const pics = Array.isArray(entry.pictures) ? entry.pictures : [];
    if (!pics.length) {
      none++;
      wordsWithNone++;
    }
    for (const pic of pics) cards.push(card(word, pic));
  }
  total += cards.length;
  sections.push({ title: pack.pack || f.replace(/\.json$/, ""), cards, note: `${cards.length} pictures, ${none} words without one` });
}

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>LinguaCards pictures</title>
<style>
:root{--bg:#fafaf7;--fg:#1d1d1b;--muted:#666;--card:#fff;--line:#ddd;--link:#0a5cc2}
@media (prefers-color-scheme:dark){:root{--bg:#161618;--fg:#ececea;--muted:#9a9a9a;--card:#222226;--line:#38383d;--link:#7db4ff}}
*{box-sizing:border-box}
body{margin:0;padding:16px;background:var(--bg);color:var(--fg);font:15px/1.4 system-ui,sans-serif}
h1{margin:0 0 4px}h2{margin:32px 0 2px;text-transform:capitalize}
.sub{color:var(--muted);margin:0 0 12px;font-size:13px}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(180px,1fr));gap:12px}
figure{margin:0;background:var(--card);border:1px solid var(--line);border-radius:8px;overflow:hidden}
img{display:block;width:100%;aspect-ratio:4/3;object-fit:cover;background:var(--line)}
figcaption{padding:8px 10px;font-size:13px}
.cap{color:var(--muted);font-size:12px}
.credit{color:var(--muted);font-size:11px;margin-top:4px;overflow-wrap:anywhere}
a{color:var(--link)}
</style>
</head>
<body>
<h1>LinguaCards pictures</h1>
<p class="sub">${total} pictures · ${wordsWithNone} of ${totalWords} words have none. Generated by scripts/contact-sheet.mjs.</p>
${sections
  .map((s) => `<h2>${esc(s.title)}</h2>\n<p class="sub">${esc(s.note)}</p>\n<div class="grid">\n${s.cards.join("\n")}\n</div>`)
  .join("\n")}
</body>
</html>
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, html);
console.log(`pictures: ${total}`);
console.log(`words with none: ${wordsWithNone} of ${totalWords}`);
console.log(`wrote ${outFile}`);
